plt.figure(figsize=(10, 8))
sns.heatmap(df_encoded[numeric_cols].corr(), annot=True, cmap='coolwarm', vmin=-1, vmax=1)
plt.title('Matriz de Correlación de Variables Numéricas')
plt.show()

